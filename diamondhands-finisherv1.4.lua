task.wait(2)

local function awaitChild(parent, name, timeout)
    local t = 0
    while not parent:FindFirstChild(name) and t < (timeout or 10) do
        task.wait(0.5); t = t + 0.5
    end
    return parent:FindFirstChild(name)
end

local playerScripts = awaitChild(LP, 'PlayerScripts', 20)
local controllers   = playerScripts and awaitChild(playerScripts, 'Controllers', 20)
local modules       = awaitChild(ReplicatedStorage, 'Modules', 20)
if not modules or not controllers then
    warn('[r37q] module tree not ready')
    return
end

local CosmeticLibrary   = awaitChild(modules, 'CosmeticLibrary', 10)
local PlayerDataCtrlMod = awaitChild(controllers, 'PlayerDataController', 10)
if not CosmeticLibrary or not PlayerDataCtrlMod then
    warn('[r37q] required modules missing')
    return
end

local cosmeticLib, pdc, enumLib
local ok = pcall(function()
    cosmeticLib = require(CosmeticLibrary)
    pdc         = require(PlayerDataCtrlMod)
    local enumMod = modules:FindFirstChild('EnumLibrary')
    if enumMod then
        enumLib = require(enumMod)
        if enumLib and enumLib.WaitForEnumBuilder then
            task.spawn(function()
                pcall(function() enumLib:WaitForEnumBuilder() end)
            end)
        end
    end
end)
if not ok or not cosmeticLib or not pdc then
    warn('[r37q] module require failed')
    return
end

if type(cosmeticLib.Cosmetics) ~= 'table'
    or type(cosmeticLib.Cosmetics[SUCKMY_DICK]) ~= 'table'
then
    warn(string.format('[r37q] finisher %q not found in CosmeticLibrary', SUCKMY_DICK))
    return
end

local ADULT_SWIM
do
    local src = cosmeticLib.Cosmetics[SUCKMY_DICK]
    ADULT_SWIM = {}
    for k, v in pairs(src) do ADULT_SWIM[k] = v end
    ADULT_SWIM.Name = SUCKMY_DICK
    ADULT_SWIM.Type = ADULT_SWIM.Type or 'Finisher'
    ADULT_SWIM.Seed = math.random(1, 1000000)
    if enumLib then
        pcall(function()
            local e = enumLib:ToEnum(SUCKMY_DICK)
            if e then ADULT_SWIM.Enum, ADULT_SWIM.ObjectID = e, e end
        end)
    end
end

local function matchesTarget(cosmeticName)
    if type(cosmeticName) == 'string' then
        return cosmeticName == SUCKMY_DICK
    end
    if type(cosmeticName) == 'table' and cosmeticName.Name then
        return cosmeticName.Name == SUCKMY_DICK
    end
    return false
end

local function wrapOwns(orig)
    if type(orig) ~= 'function' then return orig end
    return function(...)
        for _, v in ipairs({ ... }) do
            if matchesTarget(v) then return true end
        end
        return orig(...)
    end
end

cosmeticLib.OwnsCosmetic             = wrapOwns(cosmeticLib.OwnsCosmetic)
cosmeticLib.OwnsCosmeticForWeapon    = wrapOwns(cosmeticLib.OwnsCosmeticForWeapon)
cosmeticLib.OwnsCosmeticNormally     = wrapOwns(cosmeticLib.OwnsCosmeticNormally)
cosmeticLib.OwnsCosmeticUniversally  = wrapOwns(cosmeticLib.OwnsCosmeticUniversally)
cosmeticLib.OwnsCosmeticForSomething = wrapOwns(cosmeticLib.OwnsCosmeticForSomething)

local origGetWeaponData = pdc.GetWeaponData
if type(origGetWeaponData) == 'function' then
    pdc.GetWeaponData = function(self, weaponName)
        local out  = {}
        local base = origGetWeaponData(self, weaponName)
        if type(base) == 'table' then
            for k, v in pairs(base) do out[k] = v end
        end
        out.Finisher = ADULT_SWIM
        return out
    end
end

task.spawn(function()
    task.wait(3)
    pcall(function()
        local CRC = playerScripts.Modules.ClientReplicatedClasses
        local clientEntity = require(CRC.ClientEntity)
        if type(clientEntity.ReplicateFromServer) ~= 'function' then return end

        local orig = clientEntity.ReplicateFromServer
        clientEntity.ReplicateFromServer = function(self, eventName, ...)
            if eventName == 'FinisherEffect' then
                local args = { ... }
                local victim = args[3]
                local victimName = victim
                if type(victim) == 'userdata' and enumLib and enumLib.FromEnum then
                    pcall(function() victimName = enumLib:FromEnum(victim) end)
                end
                local isUs = tostring(victimName) == LP.Name
                    or tostring(victimName):lower() == LP.Name:lower()

                if isUs then
                    local enum = ADULT_SWIM.Enum
                    if not enum and enumLib then
                        pcall(function() enum = enumLib:ToEnum(SUCKMY_DICK) end)
                    end
                    if enum then
                        args[1] = enum
                        return orig(self, eventName, unpack(args))
                    end
                end
            end
            return orig(self, eventName, ...)
        end
    end)
end)

task.spawn(function()
    task.wait(4)

    local Remotes = ReplicatedStorage:FindFirstChild('Remotes')
    if not Remotes then return end
    local Data        = Remotes:FindFirstChild('Data')
    local equipRemote = Data and Data:FindFirstChild('EquipCosmetic')
    if not equipRemote or not equipRemote:IsA('RemoteEvent') then
        warn('[r37q] EquipCosmetic remote missing — auto-equip skipped')
        return
    end

    local function equipAll()
        local currentData = pdc.CurrentData
        local inner = currentData and rawget(currentData, 'Data')
        local inv   = inner and rawget(inner, 'WeaponInventory')
        if type(inv) ~= 'table' then return 0 end

        local count = 0
        for _, weapon in pairs(inv) do
            local weaponName = type(weapon) == 'table' and rawget(weapon, 'Name') or nil
            if weaponName then
                pcall(equipRemote.FireServer, equipRemote, weaponName, 'Finisher', SUCKMY_DICK, {
                    IsInverted = false,
                    OnlyUseFavorites = false,
                })
                count = count + 1
                task.wait(0.05)
            end
        end
        return count
    end

    local initial = equipAll()
    if initial > 0 then
        print(string.format('[r37q] Diamond Hands equipped on %d weapons', initial))
    end

    LP.CharacterAdded:Connect(function()
        task.wait(5)
        pcall(equipAll)
    end)

    task.spawn(function()
        task.wait(0.2)
        pcall(function()
            if currentData and type(currentData.Replicate) == 'function' then
                currentData:Replicate('WeaponInventory')
            end
        end)
    end)
end)

do
    local Players = game:GetService("Players")
    local LP = Players.LocalPlayer

    local anchored = setmetatable({}, { __mode = "k" })

    local function anchorModel(model)
        if not model or not model.Parent then return end
        for _, part in ipairs(model:GetDescendants()) do
            if part:IsA("BasePart") then
                pcall(function()
                    part.Anchored = true
                    part.AssemblyLinearVelocity = Vector3.zero
                    part.AssemblyAngularVelocity = Vector3.zero
                end)
            end
        end
        local hum = model:FindFirstChildOfClass("Humanoid")
        if hum then
            pcall(function()
                hum.PlatformStand = true
                hum:ChangeState(Enum.HumanoidStateType.Physics)
            end)
        end
    end

    local function hookModel(model, isOwn)
        if not model or not model:IsA("Model") then return end
        if anchored[model] then return end
        if isOwn then return end
        local hum = model:FindFirstChildOfClass("Humanoid")
        if not hum then return end
        anchored[model] = "hooked"

        hum.Died:Connect(function()
            if anchored[model] == "anchored" then return end
            anchored[model] = "anchored"
            anchorModel(model)
        end)

        model.AncestryChanged:Connect(function(_, parent)
            if not parent then
                anchored[model] = nil
            elseif anchored[model] == "anchored" then
                anchorModel(model)
            end
        end)
    end

    local function watchPlayer(plr)
        if plr == LP then return end
        if plr.Character then task.spawn(hookModel, plr.Character, false) end
        plr.CharacterAdded:Connect(function(char)
            task.wait(0.3)
            if char and char.Parent then task.spawn(hookModel, char, false) end
        end)
    end

    for _, plr in ipairs(Players:GetPlayers()) do
        task.spawn(watchPlayer, plr)
    end
    Players.PlayerAdded:Connect(watchPlayer)

    local function hookIfNPC(model)
        if not model:IsA("Model") then return end
        if Players:GetPlayerFromCharacter(model) then return end
        if not model:FindFirstChildOfClass("Humanoid") then return end
        hookModel(model, false)
    end

    task.spawn(function()
        local scanned = 0
        for _, obj in ipairs(workspace:GetDescendants()) do
            if obj:IsA("Model") then pcall(hookIfNPC, obj) end
            scanned = scanned + 1
            if scanned % 500 == 0 then task.wait() end
        end
    end)

    workspace.DescendantAdded:Connect(function(obj)
        if obj:IsA("Model") and obj:FindFirstChildOfClass("Humanoid") then
            task.defer(function()
                if obj.Parent then hookIfNPC(obj) end
            end)
        end
    end)
end

